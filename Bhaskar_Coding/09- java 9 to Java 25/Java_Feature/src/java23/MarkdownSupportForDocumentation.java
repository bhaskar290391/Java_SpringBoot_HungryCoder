package java23;

/**
 *  #Calculator
 *  This class used to perform calculation
 *
 *  ##Method
 *  'Add' : Adding two integer
 *  'subtract' : Subtracting two number
 */
class Calculator{
    /**
     * Adding two integer
     *
     * @param a
     * @param  b
     * @return Add method return int
     */
    public int add(int a,int b){
        return  a+b;
    }

    /**
     * Subtracting two integer
     *
     * @param  a
     * @param   b
     * @return Add method return int
     */
    public int subtract(int a,int b){
        return  a-b;
    }
}

